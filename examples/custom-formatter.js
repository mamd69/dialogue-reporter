/**
 * Example: Custom Formatter
 *
 * This example shows how to create a custom formatter
 * for Dialogue Reporter output.
 */

/**
 * Custom formatter function
 *
 * @param {CapturedData} data - The captured conversation data
 * @returns {string} - Formatted markdown string
 */
module.exports = function customFormatter(data) {
  const { sessionId, timestamp, messages, metadata } = data;

  // Simple format without syntax highlighting
  let markdown = '';

  // Header
  markdown += `# Session ${sessionId}\n\n`;
  markdown += `**Date:** ${timestamp.toLocaleString()}\n`;
  markdown += `**Messages:** ${messages.length}\n\n`;
  markdown += '---\n\n';

  // Messages in a simple format
  for (const message of messages) {
    markdown += `**${message.role.toUpperCase()}**\n`;
    markdown += message.content + '\n\n';
  }

  // Footer
  markdown += '---\n\n';
  markdown += `*Generated by Dialogue Reporter*\n`;

  return markdown;
};

/**
 * Usage:
 *
 * 1. Save this file as custom-formatter.js
 *
 * 2. In your .dialogue-reporter.json:
 *    {
 *      "customFormatter": "./custom-formatter.js",
 *      ...
 *    }
 *
 * 3. Restart Claude Code
 */
